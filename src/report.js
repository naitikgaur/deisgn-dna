import { parseColor, toHex, rotateHue, hexToHsl, seeded } from './utils.js';

const FONT_ALTERNATIVES = {
  'helvetica neue': 'Inter', helvetica: 'Inter', arial: 'Inter', 'sf pro': 'Inter', 'sf pro display': 'Inter',
  'segoe ui': 'Inter', roboto: 'Roboto Flex', circular: 'DM Sans', gotham: 'Montserrat',
  'proxima nova': 'Figtree', avenir: 'Nunito Sans', futura: 'Jost', graphik: 'Manrope',
  sohne: 'Inter Tight', 'söhne': 'Inter Tight', 'gt walsheim': 'Plus Jakarta Sans',
  'playfair display': 'Fraunces', georgia: 'Source Serif 4', 'times new roman': 'Source Serif 4',
};

const hexed = (pairs) => {
  const m = new Map();
  for (const [c, n] of pairs) {
    const p = parseColor(c);
    if (!p || p.a < 0.5) continue;
    const h = toHex(p);
    m.set(h, (m.get(h) || 0) + n);
  }
  return [...m.entries()].sort((a, b) => b[1] - a[1]);
};

const firstFamily = (stack) => stack.split(',')[0].replace(/["']/g, '').trim();

export function buildTokens(data, { remix = false, seed = Date.now() } = {}) {
  const rnd = seeded(seed);
  const bg = hexed(data.colors.background);
  const text = hexed(data.colors.text);
  const border = hexed(data.colors.border);
  const btnBgs = data.buttons.map((b) => parseColor(b.background)).filter((p) => p && p.a > 0.5).map(toHex);
  const all = [...bg, ...text, ...border].map(([h]) => h);
  const accentCandidates = [...new Set([...btnBgs, ...all])].filter((h) => { const { s, l } = hexToHsl(h); return s > 0.25 && l > 0.12 && l < 0.9; });
  const accent = accentCandidates[0] || '#4f46e5';

  const base = {
    background: bg[0]?.[0] || '#ffffff',
    surface: bg[1]?.[0] || bg[0]?.[0] || '#f8fafc',
    text: text[0]?.[0] || '#111111',
    textMuted: text[1]?.[0] || '#666666',
    border: border[0]?.[0] || '#e5e7eb',
    accent,
    accentAlt: accentCandidates[1] || accent,
  };

  const families = data.fonts.families.map(([f]) => firstFamily(f));
  const fonts = {
    body: families[0] || 'Inter',
    heading: firstFamily(data.typography.h1?.fontFamily || data.typography.h2?.fontFamily || families[0] || 'Inter'),
  };

  const radii = data.radii.map(([r]) => parseFloat(r)).filter((n) => n > 0 && n < 200).sort((a, b) => a - b);
  const radius = radii[Math.floor(radii.length / 2)] ?? 8;
  const spacing = data.spacing.map(([s]) => s).sort((a, b) => a - b);

  const original = { colors: base, fonts, radius, spacing };
  if (!remix) return { original, remix: null };

  const hueShift = (rnd() > 0.5 ? 1 : -1) * (18 + Math.round(rnd() * 22));
  const alt = (f) => FONT_ALTERNATIVES[f.toLowerCase()] || f;
  return {
    original,
    remix: {
      hueShift,
      colors: Object.fromEntries(Object.entries(base).map(([k, v]) => [k, rotateHue(v, hueShift)])),
      fonts: { body: alt(fonts.body), heading: alt(fonts.heading) },
      radius: Math.max(0, Math.round(radius * (rnd() > 0.5 ? 1.25 : 0.75))),
      spacing,
    },
  };
}

export function tokensCss(t) {
  const c = t.colors;
  return `:root {
  --color-bg: ${c.background};
  --color-surface: ${c.surface};
  --color-text: ${c.text};
  --color-text-muted: ${c.textMuted};
  --color-border: ${c.border};
  --color-accent: ${c.accent};
  --color-accent-alt: ${c.accentAlt};
  --font-body: "${t.fonts.body}", system-ui, sans-serif;
  --font-heading: "${t.fonts.heading}", system-ui, sans-serif;
  --radius: ${t.radius}px;
  /* spacing values seen (px): ${t.spacing.slice(0, 10).join(', ')} */
}
`;
}

const table = (head, rows) =>
  `| ${head.join(' | ')} |\n| ${head.map(() => '---').join(' | ')} |\n${rows.map((r) => `| ${r.join(' | ')} |`).join('\n')}\n`;

export function buildMarkdown({ url, data, tokens, screenshots, remix }) {
  const host = new URL(url).hostname;
  const t = tokens.original;
  const out = [];
  out.push(`# Design DNA: ${host}\n`);
  out.push(`> Auto-generated by **design-dna**. This file describes a *design language* (style + structure), not content. Use it as inspiration to build an **original** site.\n`);

  out.push(`## 1. Color\n`);
  out.push(table(['Role', 'Value'], Object.entries(t.colors).map(([k, v]) => [k, `\`${v}\``])));
  const g = data.colors.gradients.map(([x]) => '`' + x + '`');
  if (g.length) out.push(`\nGradients seen: ${g.join(', ')}\n`);
  out.push(`Dark mode support detected: **${data.meta.hasDarkModeQuery ? 'yes' : 'no'}**\n`);

  out.push(`## 2. Typography\n`);
  out.push(`Heading font: **${t.fonts.heading}** · Body font: **${t.fonts.body}**\n`);
  const rows = Object.entries(data.typography).filter(([, v]) => v).map(([k, v]) => [k, v.fontSize, v.fontWeight, v.lineHeight, v.letterSpacing, v.textTransform]);
  out.push(table(['Element', 'Size', 'Weight', 'Line height', 'Letter spacing', 'Transform'], rows));

  out.push(`## 3. Spacing, radius, shadows\n`);
  out.push(`- Spacing values in use (px): ${t.spacing.join(', ')}`);
  out.push(`- Typical corner radius: **${t.radius}px** (all radii: ${data.radii.map(([r]) => r).join(', ') || 'none'})`);
  out.push(`- Container widths: ${data.containerWidths.map(([w]) => w).join(', ') || 'unknown'}`);
  out.push(`- Breakpoints: ${data.breakpoints.join(', ') || 'unknown'}`);
  if (data.shadows.length) out.push(`- Shadows:\n${data.shadows.slice(0, 4).map(([s]) => `  - \`${s}\``).join('\n')}`);
  out.push('');

  out.push(`## 4. Buttons\n`);
  out.push(table(['Background', 'Text', 'Radius', 'Padding', 'Border', 'Size/Weight'], data.buttons.map((b) => [b.background, b.color, b.radius, b.padding, b.border, `${b.fontSize}/${b.fontWeight}`])));

  out.push(`## 5. Page structure (top to bottom)\n`);
  out.push(table(['#', 'Block', 'Height', 'Background', 'Inner layout', 'Contents'], data.layout.map((s, i) => [
    i + 1, `\`<${s.tag}>\``, `${s.height}px`, s.background,
    s.innerLayout ? `${s.innerLayout.display}${s.innerLayout.columns ? ` ${s.innerLayout.columns}-col` : ''}${s.innerLayout.direction ? ` ${s.innerLayout.direction}` : ''}` : 'block',
    `${s.counts.headings} headings, ${s.counts.images} media, ${s.counts.buttons} buttons, ${s.counts.cards} cards`,
  ])));

  if (Object.keys(data.cssVars).length) {
    out.push(`## 6. Source CSS variables (first 30)\n`);
    out.push('```css\n' + Object.entries(data.cssVars).slice(0, 30).map(([k, v]) => `${k}: ${v};`).join('\n') + '\n```\n');
  }

  if (remix) {
    out.push(`## 7. Remixed tokens (use these for your build)\n`);
    out.push(`Hue shift applied: **${remix.hueShift}°**. Fonts swapped for similar open-source alternatives where known.\n`);
    out.push('```css\n' + tokensCss(remix) + '```\n');
  }

  out.push(`## Screenshots (reference only)\n`);
  out.push(screenshots.map((s) => `- \`screenshots/${s}\``).join('\n') + '\n');

  out.push(`## Build rules for the AI\n`);
  out.push(`1. Recreate the **feel**: layout rhythm, density, type scale, spacing, radius, shadow style.
2. Write **all copy yourself**. Never reuse text from the source site.
3. Do **not** use the source's logo, brand name, icons, photos, illustrations or fonts that are not open-licensed.
4. Do **not** copy HTML/CSS/JS from the source. Write fresh components.
5. Change at least: palette (or hue), logo/brand, section order or hero composition, imagery, microcopy.
6. Make it responsive using the listed breakpoints and accessible (contrast, focus states, alt text).
`);
  return out.join('\n');
}
